#!/usr/bin/env python3
"""TV standard include: writes colors.inc (NC_00 .. NC_FF and the frame timing).

Every colour byte in the ROM sources is written NC_xx (the NTSC value xx). For NTSC the
table is the identity. For PAL / PAL60 the HUE nibble is replaced and the luma nibble
kept (the kernel relies on luma bits: ENAM0 reads bit 1 of PlayerColTable, the power
bar steps in luma, ...). PAL (50 Hz, 312 lines) also gets longer VBLANK / overscan
timers and a 50-frame "second" so the power bar still lasts 120 real seconds; PAL60
keeps the NTSC timing. The PAL TIA has 12 chromatic hues (2..13) and four greys
(0, 1, 14, 15), so each NTSC hue goes to the PAL hue whose colour is closest on the
Stella palettes (see tools/pal_palette.py); greys stay grey.

  gen_colors.py ntsc|pal|pal60 [OUT]        (default OUT = colors.inc)
"""
import sys
from pathlib import Path

# NTSC hue -> PAL hue, chosen by the nearest colour on Stella's 'standard' palettes
# (mean RGB distance over luma 1..7), with 0 -> 0 forced. Kept distinct for the hues
# the fixed colours use (0 grey, 1 gold, 2 orange, 4 red, 5 magenta, 6 purple,
# 8 blue, 9 cyan, C green, F brown).
# 312-line frame: NTSC runs 272 lines (V 31 + O 44 units of 64 cycles); the extra ~40
# lines (3040 cycles = ~47 units) are split between the two waits.
VBL_PAL, OVER_PAL = 51, 71

HUE_MAP = {0: 0, 1: 2, 2: 4, 3: 4, 4: 6, 5: 8, 6: 10, 7: 13, 8: 11, 9: 9,
           10: 9, 11: 7, 12: 5, 13: 3, 14: 2, 15: 4}


def pal_byte(c):
    return (HUE_MAP[(c >> 4) & 15] << 4) | (c & 0x0F)


def main() -> int:
    tv = sys.argv[1] if len(sys.argv) > 1 else "ntsc"
    out = Path(sys.argv[2] if len(sys.argv) > 2 else "colors.inc")
    if tv not in ("ntsc", "pal", "pal60"):
        sys.exit("TV must be ntsc, pal or pal60")
    lines = [f"; generated by tools/gen_colors.py ({tv}) - do not edit",
             "; NC_xx = the colour the NTSC byte xx means on this TV"]
    pal50 = tv == "pal"
    lines += [f"TV_PAL = {1 if tv != 'ntsc' else 0}      ; PAL colours",
              f"TV_50HZ = {1 if pal50 else 0}          ; 312-line, 50 Hz frame",
              f"VBL_UNITS = {VBL_PAL if pal50 else 31}      ; TIM64T units of VBLANK work window",
              f"OVER_UNITS = {OVER_PAL if pal50 else 44}     ; TIM64T units of overscan",
              f"TICKS_PER_SEC = {50 if pal50 else 60}   ; frames per power-bar step",
              f"TV_CAVE_LINES = {312 if pal50 else 272}      ; scanlines of a gameplay frame (title: 5 fewer)"]
    for c in range(256):
        v = c if tv == "ntsc" else pal_byte(c)
        lines.append(f"NC_{c:02X} = ${v:02X}")
    out.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
