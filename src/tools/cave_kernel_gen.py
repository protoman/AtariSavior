def zp_inc():
    out = ["; generated by tools/cave_kernel_gen.py - do not edit"]
    for k, v in TIA.items():
        out.append(f"{k:<14}= ${v:02X}")
    out.append("INTIM         = $0284")
    out.append("TIM64T        = $0296")
    out.append("Tmp           = $00             ; `bit Tmp` is a 3-cycle filler (reads TIA $00)")
    for k, v in LIVE.items():
        out.append(f"{k:<14}= ${v:02X}")
    out.append("P0Top         = RoomY           ; the player's first row IS RoomY")
    for k, v in KERNEL_ZP.items():
        out.append(f"{k:<14}= ${v:02X}")
