HUD_PAD = ["$A9", "$01", "$8D", "<BK_HUD", ">BK_HUD", "$4C", "$40", "$F5"]   # lda #1/sta BK_HUD/jmp $F540
FRAMES = ["PlayerSpriteA", "PlayerSpriteB", "PlayerWalkA", "PlayerWalkB"]
DESIGNS = ["OBJ_KEY", "OBJ_CELL", "OBJ_MOTH", "OBJ_SPIDER", "OBJ_LAMP", "OBJ_TENTACLE", "OBJ_BAT",
           "OBJ_SNAKE", "OBJ_MINER", "OBJ_BOMB", "OBJ_RAFT", "OBJ_LAMP_R"]
DESIGN_ROWS = {"OBJ_KEY": 12, "OBJ_CELL": 4, "OBJ_MOTH": 14, "OBJ_SPIDER": 15, "OBJ_LAMP": 10,
               "OBJ_TENTACLE": 14, "OBJ_BAT": 10, "OBJ_SNAKE": 6, "OBJ_MINER": 16, "OBJ_BOMB": 8,
               "OBJ_RAFT": 2, "OBJ_LAMP_R": 10}
HUD_PAD_AT = 0x68             # page $FC: the HUD fold pad bytes live here
FRAME3_BASE = 112             # frame 3 (WalkB) gfx block inside page $FC (after the pad)

SMALL_ROM = """NAROM:       .byte 10,10,10,244            ; nA: 10 (bands 0-2), 12+off (band 3) - 24
TideMask:    .byte 0,0,0,$FF
WaterXROM:   .byte $30,$30,$30,0
"""


def _bytes_after(lines, label, stop):
    i = next(n for n, l in enumerate(lines) if re.match(rf"^{label}:", l))
    toks = []
    for l in lines[i + 1:]:
        if stop(l):
            break
        code = l.split(";")[0].strip()
        if code.startswith(".byte"):
            toks += [t.strip() for t in code[5:].split(",") if t.strip()]
    return toks


def _num(t):
    return int(t[1:], 2) if t.startswith("%") else int(t.lstrip("$"), 16) if t.startswith("$") else int(t)


def read_art(kernel_asm):
    lines = Path(kernel_asm).read_text().splitlines()
    label = re.compile(r"^[A-Za-z_]\w*:")
    art = {}
    for f in FRAMES:
        toks = _bytes_after(lines, f, lambda l: bool(label.match(l)) or l.startswith(".ds"))
        assert len(toks) == H0, (f, len(toks))
        art[f] = [_num(t) for t in toks]
    art["col0"] = _bytes_after(lines, "PlayerColTable", lambda l: bool(label.match(l))
                               or l.startswith(".ds") or l.startswith("; UEPrologue"))
    assert len(art["col0"]) == H0, len(art["col0"])
    spr = _bytes_after(lines, "ObjSprites", lambda l: l.startswith("; Enemy type") or bool(label.match(l)))
    art["spr"] = [_num(t) for t in spr]
    art["col"] = _bytes_after(lines, "ObjColorTab",
                              lambda l: l.startswith("; ----------------------------------------------------------"))
    consts = {}
    for l in lines:
        m = re.match(r"^(OBJ_[A-Z_]+)\s*=\s*(\d+)", l)
        if m:
            consts[m.group(1)] = int(m.group(2))
    art["consts"] = consts
    return art


def test_art():
    """Tagged art for tools/proto: P0 gfx = $80|frame<<5|row, colour = $40+2*row; P1 gfx =
    $80|row, colour = $10+2*design (non zero for every row that has gfx)."""
    art = {"consts": {}}
    run = 0
    spr, col = [], []
    for i, d in enumerate(DESIGNS):
        art["consts"][d] = run
        for r in range(DESIGN_ROWS[d]):
            spr.append(0x80 | r)
            col.append(f"${0x10 + 2 * i:02X}")
        run += DESIGN_ROWS[d]
    art["spr"], art["col"] = spr, col
    for fi, f in enumerate(FRAMES):
        art[f] = [0x80 | (fi << 5) | r for r in range(H0)]
    art["col0"] = [f"${0x40 + 2 * r:02X}" for r in range(H0)]
    return art


def tables(art):
    """-> (pages text, luts text, layout dict for the harness)."""
    c = art["consts"]
    assert sum(DESIGN_ROWS.values()) == len(art["spr"]) == len(art["col"]), (
        sum(DESIGN_ROWS.values()), len(art["spr"]), len(art["col"]))
    run = 0
    for d in sorted(DESIGNS, key=lambda d: c[d]):
        assert c[d] == run, (d, c[d], run)
        run += DESIGN_ROWS[d]
    designs = sorted(DESIGNS, key=lambda d: c[d])
    data = {n: ["0"] * 256 for n in PAGES}
    # P0 frames 0-2 on page FF (bases 0, 60, 120; reads end below index 216, the vectors are
    # at $FFFA); frame 3 on page FC at FRAME3_BASE
    frame_loc = []
    stride0 = PAD + H0 + 1
    for fi, f in enumerate(FRAMES):
        if fi < 3:
            pg, base = "CaveP0G0", stride0 * fi
        else:
            pg, base = "CaveP0C", FRAME3_BASE
        for r, v in enumerate(art[f]):
            data[pg][base + PAD + r] = f"${v:02X}"
        frame_loc.append((PAGES[pg], PAD + H0 + base))
    for r, t in enumerate(art["col0"]):
        data["CaveP0C"][PAD + r + 1] = t              # colour of row r is read at gfx index r+1
    for k, v in enumerate(HUD_PAD):
        assert data["CaveP0C"][HUD_PAD_AT + k] == "0"
        data["CaveP0C"][HUD_PAD_AT + k] = v
    design_loc = []
    run = 0
    for i, d in enumerate(designs):
        pg, slot = divmod(i, 4)
        base = P1_STRIDE * slot
        h = DESIGN_ROWS[d]
        for r in range(h):
            g, col = art["spr"][run + r], art["col"][run + r]
            data[f"CaveP1G{pg}"][base + PAD + r] = f"${g:02X}"
            data[f"CaveP1C{pg}"][base + PAD + r] = col
            assert g == 0 or col not in ("NC_00", "0", "$00"), (d, r)
        run += h
        design_loc.append((PAGES[f"CaveP1G{pg}"], PAGES[f"CaveP1C{pg}"], PAD + H1 + base))
    txt = ""
    for n in sorted(PAGES, key=lambda n: PAGES[n]):
        txt += f"    ORG ${PAGES[n]:02X}00\n{n}:\n"
        top = 0xFA if PAGES[n] == 0xFF else 256      # $FFFA-$FFFF = the vectors (never read:
        for i in range(0, top, 16):                   #   frames 0-2 read up to index 215)
            txt += "    .byte " + ",".join(data[n][i:min(i + 16, top)]) + "\n"
    assert max(i for i, v in enumerate(data["CaveP0G0"]) if v != "0") < 0xFA - 36
    luts = f"""CAVE_P0CHI   = ${PAGES['CaveP0C']:02X}
CAVE_NDESIGN = {len(designs)}
CaveDesignOff:  .byte {",".join(str(c[d]) for d in designs)}
CaveDesignGHi:  .byte {",".join(f"${g:02X}" for g, _, _ in design_loc)}
CaveDesignCHi:  .byte {",".join(f"${cc:02X}" for _, cc, _ in design_loc)}
CaveDesignKb:   .byte {",".join(str(k) for _, _, k in design_loc)}
CaveFrameGHi:   .byte {",".join(f"${g:02X}" for g, _ in frame_loc)}
CaveFrameKb:    .byte {",".join(str(k) for _, k in frame_loc)}
CaveFineTab:    .byte $70,$60,$50,$40,$30,$20,$10,$00,$F0,$E0,$D0,$C0,$B0,$A0,$90
"""
    idx = [0] * (max(c[d] for d in designs) // 2 + 1)      # indexed by ObjBase >> 1
    for i, d in enumerate(designs):
        assert idx[c[d] // 2] == 0 and (c[d] // 2 or i == 0), "ObjBase >> 1 must be unique"
        idx[c[d] // 2] = i
    lut = "CAVE_IDXLEN = %d\nCaveDesignIdx:\n" % len(idx)
    for i in range(0, len(idx), 16):
        lut += "    .byte " + ",".join(str(v) for v in idx[i:i + 16]) + "\n"
    layout = {"frames": frame_loc, "designs": design_loc, "design_names": designs}
    return txt, luts, layout, lut


def main():
    mode = sys.argv[1]
    out = Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    art = test_art() if mode == "--test" else read_art(sys.argv[3])
    txt, luts, _, lut = tables(art)
    (out / "cave_luts.inc").write_text(luts + lut)       # the prologue's tables (bank7)
    (out / "cave_small.inc").write_text(SMALL_ROM)       # the kernel's own ROM tables (bank6)
    (out / "cave_zp.inc").write_text(zp_inc())
    (out / "cave_kernel.inc").write_text(kernel())
    (out / "cave_prologue.inc").write_text(prologue_core())
    (out / "cave_prime.inc").write_text(prime_core())
    (out / "cave_tables.inc").write_text(txt)


if __name__ == "__main__":
    main()
