#!/usr/bin/env python3
"""Generator for the bank6 gameplay cave kernel (plans/hero_style_kernel_progress.md).

Writes (to OUTDIR):
  cave_zp.inc        zero page map (kernel-local state + the live bytes the kernel reads)
  cave_kernel.inc    the kernel: one band code run 4x (X = band), generated line by line
  cave_tables.inc    padded sprite pages + LUTs (production: parsed from kernel.asm art;
                     --test: tagged art for tools/proto)

Every scanline is a Timeline: instructions sit at exact cycle targets (padding with nop /
bit), so the store phases are asserted at generation time.

Sprite fetch (branch free): ONE shared Y = line counter inside a segment, four zero page
pointers G0/C0 (player gfx/colour) and G1/C1 (object gfx/colour). A pointer's HI byte is a
per-frame constant (page of the frame/design), its LO byte S is the start offset inside the
padded block and is rewritten once per 36-line segment (line 2 of every band, `ldy #0`).

  c5   lda (C0),Y / sta COLUP0 / and LaserState / sta ENAM0     (colour of THIS line)
  c19  lda (G0),Y / sta GRP0                                    (row for the NEXT line)
  c27..c50  free window (playfield stores, segment update, next-segment arithmetic)
  c50  lda (G1),Y / sta GRP1 (write c57, latches P0 via VDELP0)
  c58  beq: gfx==0 -> COLUP1 = BandCol (M1/door strip shares COLUP1), else (C1),Y; 13c both
  c71  iny / c73 sta WSYNC

Second object ("slot 1"): the P1 context (pointer pages, K, e) exists twice (arrays at
$F8-$FF indexed by ctx = Band >= Slot1Band); band Slot1Band hooks the pad of its update line
(`cpx Slot1Band / beq`) into a partial line + a variable positioning line + the HMOVE line.
"""
