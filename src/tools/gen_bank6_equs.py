#!/usr/bin/env python3
"""generated/bank6_equs.inc: the few bank0 addresses the bank6 cave kernel needs, read from
bank0's symbol dump (dasm -s). build.sh runs it after bank0 and before bank6.

  Kernel6Pad    the byte after bank0's `sta $1FFA` (bank6 puts `jmp Kernel6Entry` there)
  PlayerSpriteA/B, PlayerWalkA/B   the four player frames (prologue maps Grp0Ptr -> frame)
"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1]
sym = {}
for line in (root / "generated" / "symbols.asm").read_text().splitlines():
    m = re.match(r"^(\S+)\s+([0-9a-fA-F]{4})\b", line)
    if m:
        sym[m.group(1)] = int(m.group(2), 16)
need = ["0.TitleKernel", "GoKernel6", "PlayerSpriteA", "PlayerSpriteB", "PlayerWalkA", "PlayerWalkB"]
missing = [n for n in need if n not in sym]
if missing:
    sys.exit(f"gen_bank6_equs: missing symbols {missing}")
assert sym["0.TitleKernel"] == sym["GoKernel6"] + 3, "dispatch pad is not `sta abs` + next byte"
out = ["; generated by tools/gen_bank6_equs.py from bank0's symbols - do not edit"]
out.append(f"Kernel6Pad      = ${sym['0.TitleKernel']:04X}")
for n in need[2:]:
    out.append(f"{n:<15} = ${sym[n]:04X}")
(root / "generated" / "bank6_equs.inc").write_text("\n".join(out) + "\n")
