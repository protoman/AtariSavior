#!/usr/bin/env python3
"""Generate the Phase-6 QA stage (throwaway stage, committed under
src/tests/qa/rooms) — one room per feature in a walkable chain.

This is the DURABLE generator: the stage used to be generated by an ad-hoc
script in /tmp (lost with the temp dir). Re-run it after editing the layouts,
rebuild with tools/qa_build.sh, then re-run tools/qa_sweep.py.

Format note (2026-10-17 async move): the models hold the SHAPE only. A feature
char in a layout row (P/C) becomes SOLID_WALL in the model (same PF byte —
tile_to_char always drew it solid) and the ROOM carries the behaviour cell in
feature_cells. That is exactly what tools/migrate_async_to_rooms.py does to
real data, so authoring here in the readable P/V/C form is safe.

Layout rules that make the chain traversable (learned the hard way):
  * the player's collision box is [RoomX-7, RoomX], so an 8px one-cell gap is a
    1px drop window — every lane is TWO cells (16px);
  * every room's entry gap and the previous room's exit gap are the same cells;
  * a room the player must WALK in needs a floor (row2 solid at the landing
    cell) plus a gap further along the walk;
  * an M1 door can never be touched while falling (the wall-hide envelope
    forbids its column and mirror from being open in rows 0/2 — which are the
    fall path), so the door room has a floor and the player walks into the bar;
  * a full-band phase stripe is not crossable in one pass, so the phase room
    routes the lane AROUND it (see AGENTS: phase = one-time crushable wall);
  * a bottom_band WATER room kills at RoomY >= 125, so its crossing is a
    row-2 platform/raft BRIDGE the player walks (the water on either side is
    the hazard); down-exit is impossible there, so the goal (miner) lives at
    the far end instead of a further room.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
QA = ROOT / "tests" / "qa" / "rooms"
T = {".": 0, "#": 1, "R": 6, "H": 8, "P": 10, "C": 12}
FEATURE_TILES = (10, 12)
SOLID_WALL = 1

# (id, name, row0, row1, row2, asym_patches|None)
MODELS = [
    (20, "QA start",    "###..#####", "#.........", "######..##", None),
    (21, "QA key",      "######..##", "#.........", "######..##", None),
    (22, "QA phase",    "######..##", "#.......PP", "####..####", None),
    (23, "QA door",     "####..####", "..........", "##..######", [[1, 0, 9]]),
    (24, "QA clear",    "##..######", "#.........", "##..######", None),
    (25, "QA hcrunch",  "##..######", "CCCCCCCCCC", "##..######", None),
    # Water room: cells 0,1 are OPEN (the killing water), 2,3 the entry ledge
    # (matched to the hcrunch exit lane), 4-7 the RAFT bridge, 8,9 the far
    # ledge the miner sits on.
    (26, "QA water",    "##..######", "#.........", "..##RRRR##", None),
]
CHAIN = [20, 21, 22, 23, 24, 25, 26]          # rooms 0..6
KEY_ROOM = 1
WATER_ROOM = 6
PALETTE = (112, 40, 0, 132, 68, 20)           # live level-1 browns
WATER_RGB = (0, 70, 190)                      # blue band (nearest TIA byte)


def main() -> None:
    (QA / "models").mkdir(parents=True, exist_ok=True)
    rows_of = {}
    models = []
    for mid, name, r0, r1, r2 in [(m[0], m[1], m[2], m[3], m[4]) for m in MODELS]:
        rows = [r0, r1, r2]
        rows_of[mid] = rows
        tiles = []
        for row in rows:
            for ch in row:
                t = T[ch]
                # features are ROOM cells: the model keeps a solid shape
                tiles.append(SOLID_WALL if t in FEATURE_TILES else t)
        # NOTE: the strip/door patch goes on the ROOM (room.asym_patches) —
        # a model that still carries asym_patches is stale and convert fails.
        models.append({"id": mid, "name": name, "width": 10, "height": 3,
                       "tiles": tiles})
    (QA / "models" / "models.json").write_text(
        json.dumps({"models_file": {"models": models}}, indent=1) + "\n")

    def features_of(mid):
        # one cell per (row, kind) at its lowest column: a feature is a row
        # property (convert resolves the row) — see the editor change 2026-10-18
        seen = {}
        for r, row in enumerate(rows_of[mid]):
            for c, ch in enumerate(row):
                if T[ch] in FEATURE_TILES:
                    key = (r, T[ch])
                    if key not in seen or c < seen[key]:
                        seen[key] = c
        out = [[r, c, t] for (r, t), c in sorted(seen.items())]
        return out or None

    key = {"type": 6, "x": 13.0, "y": 5.0, "range_min": 13.0,
           "range_max": 13.0, "speed": 1.0, "dir": 1}

    def room(rid, mid, enemies=None, water=False):
        r = {"room_id": rid, "model_id": mid, "room_x": 0, "room_y": rid,
             "enemies": enemies or [], "lamps": [],
             "bottom_band": water, "bottom_r": 0, "bottom_g": 0,
             "bottom_b": 0}
        if water:
            r["bottom_r"], r["bottom_g"], r["bottom_b"] = WATER_RGB
        f = features_of(mid)
        if f:
            r["feature_cells"] = f
        asym = next(x[5] for x in MODELS if x[0] == mid)
        if asym:
            r["asym_patches"] = asym
        return r

    rooms = [room(i, mid, [key] if i == KEY_ROOM else None,
                  water=(i == WATER_ROOM))
             for i, mid in enumerate(CHAIN)]

    def level(n, name, rooms_, miner_room, miner_x, miner_y):
        return {"cereal_class_version": 1, "level_id": n, "name": name,
                "wall_r": PALETTE[0], "wall_g": PALETTE[1],
                "wall_b": PALETTE[2], "wall2_r": PALETTE[3],
                "wall2_g": PALETTE[4], "wall2_b": PALETTE[5],
                "start_room": 0, "miner_room": miner_room,
                "miner_x": miner_x, "miner_y": miner_y, "miner_dir": 1,
                "rooms": rooms_}

    # The miner sits on the water room's far ledge: cell 8 = x64-71 ->
    # MINER_X = enemy_x_px(8*2=16) = 71; standing height on the ledge = y84.
    levels = {1: level(1, "QA sweep", rooms, WATER_ROOM, 8.0, 7.0)}
    for n in (2, 3, 4):
        levels[n] = level(n, f"QA filler {n}", [room(0, 20)], 0, 2.5, 7.0)

    for n, lvl in levels.items():
        (QA / f"level_{n:03d}.json").write_text(
            json.dumps({"level": lvl}, indent=1) + "\n")
        for r in lvl["rooms"]:
            # the room txt is the RESOLVED grid (feature cells included), the
            # same text convert_level writes next to the live data
            (QA / f"level_{n:03d}_room_{r['room_id'] + 1:03d}.txt").write_text(
                "\n".join(rows_of[r["model_id"]]) + "\n")
    print(f"wrote {QA}: models {[m[0] for m in MODELS]}, "
          f"level 1 rooms {len(rooms)}")


if __name__ == "__main__":
    main()
