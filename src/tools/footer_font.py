#!/usr/bin/env python3
"""Intro copyright footer packer — bank2 FooterFont (FooterBand, 48px).

Text: "2026 Iuri Fiedoruk" (user 2026-10-11; fallback "2026 Iuri Fdrk"
if it did not fit — it does: 46px of the 48px canvas).

Engine: the proven 48px sprite technique (6 windows x 8px, NUSIZ3
P0/P1 interleave; FooterBand .FooterLoop draws Y=7..1 = 7 scanlines,
byte0 never drawn). Format (reverse-engineered + round-trip verified
against the shipped font):
  * 6 sprites x 8 bytes, asm line k = sprite k = canvas columns 8k..8k+7
  * byte index j == draw order: j=7 is the FIRST (top) scanline,
    j=1 the last drawn, j=0 never drawn
  * bit 0x80>>i = pixel i (MSB = leftmost of the 8px window)
  * glyph ink occupies canvas rows 1..5 (rows 0 and 6 stay blank)

Type: 3x5 px glyphs (14 letters/digits at 3px + 1px 'i' x2 + 1px
spaces x2 = 46px <= 48px). The old 4px font could hold only
"2026 Iuri" (33px); + "Fiedoruk" needs the 3px set.

Run:  /home/iuri/python3/bin/python3 tools/footer_font.py [--check]
  --check  verify the FooterFont block in bank2.asm still matches
           this generator (CI-style; hand edits fail loudly).
"""
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent
BANK2 = SRC / "bank2.asm"

TEXT = "2026 Iuri Fiedoruk"
CANVAS_W = 48
ROWS = 7                       # drawn rows = canvas 0..6 (byte7..byte1)

# 3x5 glyphs; width may be 1 (i, space) or 3. 5 rows top->bottom.
GLYPHS = {
    " ": ["0", "0", "0", "0", "0"],
    "0": ["111", "101", "101", "101", "111"],
    "2": ["111", "001", "010", "100", "111"],
    "6": ["110", "100", "111", "101", "111"],
    "I": ["111", "010", "010", "010", "111"],
    "u": ["101", "101", "101", "101", "111"],
    "r": ["110", "101", "100", "100", "100"],
    "i": ["1", "0", "1", "1", "1"],          # dot + 1px stem
    "F": ["111", "100", "110", "100", "100"],
    "e": ["111", "101", "110", "100", "111"],
    "d": ["001", "001", "111", "101", "111"],
    "o": ["111", "101", "101", "101", "111"],
    "k": ["101", "110", "100", "110", "101"],
}
GLYPH_TOP_ROW = 1              # ink rows 1..5; rows 0 and 6 blank


def build_canvas(text):
    for ch in text:
        if ch not in GLYPHS:
            raise SystemExit(f"missing glyph: {ch!r}")
        g = GLYPHS[ch]
        if len(g) != 5 or len({len(r) for r in g}) != 1:
            raise SystemExit(f"{ch!r}: glyph must be 5 rows, ragged width")
    canvas = [["."] * CANVAS_W for _ in range(ROWS)]
    x = 0
    layout = []
    for ch in text:
        g = GLYPHS[ch]
        w = len(g[0])
        if x + w > CANVAS_W:
            raise SystemExit(f"overflow at {ch!r}: x={x} + {w} > {CANVAS_W}")
        layout.append((ch, x, w))
        for r in range(5):
            for i, bit in enumerate(g[r]):
                canvas[GLYPH_TOP_ROW + r][x + i] = "#" if bit == "1" else "."
        x += w
    return canvas, x, layout


def slots_bytes(canvas):
    """6 sprites x 8 bytes: byte j draws canvas row (7 - j); j=0 unused."""
    out = []
    for slot in range(6):
        rowbytes = [0]                       # byte0: never drawn
        for j in range(1, 8):                # byte1..byte7 = rows 6..0
            row = 7 - j
            b = 0
            for i in range(8):
                x = slot * 8 + i
                if canvas[row][x] == "#":
                    b |= 0x80 >> i
            rowbytes.append(b)
        out.append(rowbytes)
    return out


def render_block(slots):
    lines = ["FooterFont:",
              "    ; generated by tools/footer_font.py — DO NOT EDIT",
              f'    ; "{TEXT}" packed into the 48px footer canvas',
              "    ; (6 x 8px sprites, FooterBand .FooterLoop: Y=7..1)."]
    for k, rowbytes in enumerate(slots):
        vals = ", ".join(f"${b:02X}" for b in rowbytes)
        lines.append(f"    .byte {vals}    ; sprite {k} (x {k*8}-{k*8+7})")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv
    canvas, used, layout = build_canvas(TEXT)
    print(f'TEXT: "{TEXT}"  ink {used}px / {CANVAS_W}px')
    print("layout: " + " ".join(f"{ch}@{x}" for ch, x, w in layout))
    for row in canvas:
        print("   " + "".join(row))
    slots = slots_bytes(canvas)

    src = BANK2.read_text()
    m = re.search(r"^FooterFont:\n(?:.*\n)*?(?=    \.ds \$F830)", src, re.M)
    if not m:
        sys.exit("FooterFont block not found in bank2.asm")
    block = render_block(slots)
    if check:
        if m.group(0) != block:
            print("FAIL: bank2.asm FooterFont differs from generator")
            sys.exit(1)
        print("bank2 FooterFont matches generator")
        return
    src = src[:m.start()] + block + src[m.end():]
    BANK2.write_text(src)
    print(f"patched {BANK2.relative_to(SRC)} FooterFont ({len(block) - len(m.group(0)):+d}B text)")


if __name__ == "__main__":
    main()
