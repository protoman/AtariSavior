#!/usr/bin/env python3
"""Intro copyright footer packer — bank2 FooterFont (FooterBand, 48px).

Two-line layout (user 2026-10-11/12):
    2026 Iuri
       Fiedoruk
Line 2 is indented so its F sits under line 1's I (18px with 1px
inter-letter spacing). The 7-row canvas made the text too short (user
2026-10-12), so the canvas grows to 13 rows: line 1 = rows 0-4, gap
rows 5-7, line 2 = rows 8-12 (two 5px lines + 3-row gap). Glyphs are
3 wide x 5 tall (1px 'i'/space); 1px gap between every glyph (user
2026-10-12). Line widths: "2026 Iuri" 31px, "Fiedoruk" 29px <= 48px.

Engine: the proven 48px sprite technique (6 windows x 8px, NUSIZ3
P0/P1 interleave; FooterBand .FooterLoop draws Y=13..1 = 13 scanlines,
byte0 never drawn). Format (round-trip verified against the shipped
font):
  * 6 sprites x 14 bytes, asm line k = sprite k = canvas columns 8k..8k+7
  * byte index j == draw order: j=13 is the FIRST (top) scanline,
    j=1 the last drawn, j=0 never drawn
  * bit 0x80>>i = pixel i (MSB = leftmost of the 8px window)

Glyph widths: most letters 3px, 'i' and space 1px (proportional, so
the 48px canvas holds the full name on each line).

Run:  /home/iuri/python3/bin/python3 tools/footer_font.py [--check]
  --check  verify the FooterFont block in bank2.asm still matches
           this generator (CI-style; hand edits fail loudly).
"""
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent
BANK2 = SRC / "bank2.asm"

# (text, indent-in-pixels); line 2 indent 18 = F under line 1's I
# (I sits at col 18 once the 1px inter-letter gaps are counted).
LINES = [
    ("2026 Iuri", 0),
    ("Fiedoruk", 18),
]
CANVAS_W = 48
ROWS = 13                       # drawn rows = canvas 0..12 (byte13..byte1)
LINE_ROWS = 5                   # each line is 5 rows tall
GAP_ROWS = 3                    # blank rows between the two lines

# 3x5 glyphs; width 1 (i, space) or 3. 5 rows top->bottom.
GLYPHS = {
    " ": ["0", "0", "0", "0", "0"],
    "0": ["111", "101", "101", "101", "111"],
    "2": ["111", "001", "111", "100", "111"],
    "6": ["111", "100", "111", "101", "111"],
    "I": ["111", "010", "010", "010", "111"],
    "u": ["101", "101", "101", "101", "111"],
    "r": ["110", "101", "100", "100", "100"],
    "i": ["1", "0", "1", "1", "1"],              # dot, gap, stem (1px wide)
    "F": ["111", "100", "110", "100", "100"],
    "e": ["111", "101", "111", "100", "111"],
    "d": ["001", "001", "111", "101", "111"],
    "o": ["111", "101", "101", "101", "111"],
    "k": ["101", "110", "110", "110", "101"],
}


def build_canvas():
    for text, _ in LINES:
        for ch in text:
            if ch not in GLYPHS:
                raise SystemExit(f"missing glyph: {ch!r}")
            g = GLYPHS[ch]
            if len(g) != LINE_ROWS or len({len(r) for r in g}) != 1:
                raise SystemExit(f"{ch!r}: glyph must be {LINE_ROWS} rows, ragged width")
    canvas = [["."] * CANVAS_W for _ in range(ROWS)]
    layout = []
    for li, (text, indent) in enumerate(LINES):
        top = li * (LINE_ROWS + GAP_ROWS)       # line 0 -> row 0, line 1 -> row 8
        if top + LINE_ROWS > ROWS:
            raise SystemExit(f"line {li} overflows the {ROWS}-row canvas")
        x = indent
        for ch in text:
            g = GLYPHS[ch]
            w = len(g[0])
            if x + w > CANVAS_W:
                raise SystemExit(f"overflow at {ch!r}: x={x} + {w} > {CANVAS_W}")
            layout.append((ch, x, w, li))
            for r in range(LINE_ROWS):
                for i, bit in enumerate(g[r]):
                    canvas[top + r][x + i] = "#" if bit == "1" else "."
            x += w + 1                          # 1px gap between glyphs
    return canvas, layout


def slots_bytes(canvas):
    """6 sprites x 14 bytes: byte j draws canvas row (13 - j); j=0 unused."""
    out = []
    for slot in range(6):
        rowbytes = [0]                       # byte0: never drawn
        for j in range(1, 14):               # byte1..byte13 = rows 12..0
            row = ROWS - j
            b = 0
            for i in range(8):
                x = slot * 8 + i
                if canvas[row][x] == "#":
                    b |= 0x80 >> i
            rowbytes.append(b)
        out.append(rowbytes)
    return out


def render_block(slots):
    lines = ["FooterFont:",
             "    ; generated by tools/footer_font.py — DO NOT EDIT",
             '    ; "2026 Iuri / Fiedoruk" (two lines, 3x5 glyphs) packed into',
             "    ; the 48px x 13-row footer canvas (6 x 14-byte sprites,",
             "    ; FooterBand .FooterLoop: Y=13..1)."]
    for k, rowbytes in enumerate(slots):
        vals = ", ".join(f"${b:02X}" for b in rowbytes)
        lines.append(f"    .byte {vals}    ; sprite {k} (x {k*8}-{k*8+7})")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv
    canvas, layout = build_canvas()
    for li, (text, indent) in enumerate(LINES):
        print(f'line {li}: "{text}" @col {indent}')
    print("layout: " + " ".join(
        f"{ch}@{x}" for ch, x, w, li in layout if li == 0))
    print("         " + " ".join(
        f"{ch}@{x}" for ch, x, w, li in layout if li == 1))
    for row in canvas:
        print("   " + "".join(row))
    slots = slots_bytes(canvas)

    src = BANK2.read_text()
    m = re.search(r"^FooterFont:\n(?:.*\n)*?(?=    \.ds \$F854)", src, re.M)
    if not m:
        sys.exit("FooterFont block not found in bank2.asm")
    block = render_block(slots)
    if check:
        if m.group(0) != block:
            print("FAIL: bank2.asm FooterFont differs from generator")
            sys.exit(1)
        print("bank2 FooterFont matches generator")
        return
    src = src[:m.start()] + block + src[m.end():]
    BANK2.write_text(src)
    print(f"patched {BANK2.relative_to(SRC)} FooterFont")


if __name__ == "__main__":
    main()
