#!/home/iuri/python3/bin/python3
"""Generate art/intro_theme.asm from the readable theme (2026-10-20).

The theme is 'Hollow Earth' (original, 2026-10-16), E minor, single voice on
the TIA Lead ($0C). It was stored as (duration, note) byte pairs = 102 B; the
player walks it one step per note, so the pairs compact to ONE byte per step:

    byte = note_code * 4 + duration_code
    note_code   = AUDF value (all theme pitches are <= $1F)
                  $3E = rest (silence, the step's duration still runs)
                  $3F = loop (reset the pointer; its duration code is 3 = 0)
    duration_code indexes MelDur = $1E (30 frames), $3C (60), $78 (120), 0

bank1's MusicTick unpacks: note code = byte >> 2, duration code = byte & 3.
Only 3 real durations + the loop step's 0 exist, and there are 14 pitches +
2 sentinels, so both fields are exact (no data loss).

Run: /home/iuri/python3/bin/python3 tools/gen_intro_theme.py [--check]
--check re-expands the generated file and asserts it reproduces the pairs.
"""
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent
OUT = SRC / "src/art/intro_theme.asm"

DURATIONS = {0x1E: 0, 0x3C: 1, 0x78: 2, 0x00: 3}
MELDUR = (0x1E, 0x3C, 0x78, 0x00)

THEME = [
    (0x1E, 0x1F), (0x1E, 0x1B), (0x1E, 0x1A), (0x1E, 0x17), (0x3C, 0x14), (0x1E, 0x13),
    (0x1E, 0x14), (0x1E, 0x17), (0x1E, 0x1A), (0x1E, 0x1B), (0x1E, 0x1F), (0x3C, 0x1F),
    (0x3C, 0xFE), (0x1E, 0x1F), (0x1E, 0x1A), (0x1E, 0x1F), (0x1E, 0xFE), (0x78, 0x0F),
    (0x1E, 0x0F), (0x1E, 0x0D), (0x1E, 0x0B), (0x1E, 0x09), (0x3C, 0x08), (0x1E, 0x09),
    (0x1E, 0x08), (0x3C, 0x07), (0x1E, 0x09), (0x1E, 0x08), (0x78, 0x07), (0x1E, 0x1F),
    (0x1E, 0x1F), (0x1E, 0x1A), (0x1E, 0x1A), (0x1E, 0x17), (0x1E, 0x17), (0x3C, 0x14),
    (0x3C, 0x13), (0x3C, 0x12), (0x3C, 0x13), (0x3C, 0x14), (0x78, 0x1F), (0x1E, 0x0F),
    (0x1E, 0x10), (0x1E, 0x0F), (0x1E, 0x0D), (0x3C, 0x0B), (0x3C, 0x09), (0x3C, 0x08),
    (0x3C, 0x07), (0x78, 0x1F), (0x00, 0xFF),
]

REST = 0xFE
LOOP = 0xFF
REST_CODE = 0x3E                 # 6-bit note field cannot hold $FE/$FF
LOOP_CODE = 0x3F


def pack(pairs):
    out = []
    for dur, note in pairs:
        code = REST_CODE if note == REST else LOOP_CODE if note == LOOP else note
        assert dur in DURATIONS, f"duration ${dur:02X} has no code"
        assert code <= LOOP_CODE, f"note ${note:02X} does not fit 6 bits"
        out.append(code * 4 + DURATIONS[dur])
    return out


def unpack(packed):
    return [(MELDUR[b & 3],
             REST if b >> 2 == REST_CODE else LOOP if b >> 2 == LOOP_CODE else b >> 2)
            for b in packed]


def emit(packed):
    lines = [
        "; Intro theme: 'hollow earth' - adventurous, with dread (original, 2026-10-16).",
        "; GENERATED by tools/gen_intro_theme.py - edit the pairs there, not here.",
        "; E minor; every AUDF is in tune on the TIA Lead ($0C). Single voice.",
        "; One byte per step: note code * 4 + duration code.",
        ";   note code = AUDF ($3E = rest, $3F = loop); duration code -> MelDur.",
        "MusicMel:",
    ]
    for i in range(0, len(packed), 16):
        lines.append("    .byte " + ",".join("$%02X" % b for b in packed[i:i + 16]))
    lines.append("MelDur:                         ; duration code -> frames")
    lines.append("    .byte " + ",".join("$%02X" % b for b in MELDUR))
    return "\n".join(lines) + "\n"


def main():
    packed = pack(THEME)
    text = emit(packed)
    assert unpack(packed) == THEME, "pack/unpack mismatch"
    if "--check" in sys.argv:
        body = "\n".join(line.split(";")[0] for line in OUT.read_text().splitlines())
        got = [int(x, 16) for x in re.findall(r"\$([0-9A-F]{2})", body)]
        assert got[:len(packed)] == packed, "art/intro_theme.asm is stale - regenerate"
        assert unpack(got[:len(packed)]) == THEME, "generated theme differs from the pairs"
        print(f"gen_intro_theme: OK ({len(packed)} steps, {len(packed)} B)")
        return
    OUT.write_text(text)
    print(f"gen_intro_theme: wrote {OUT.name} ({len(packed)} steps, {len(packed)} B)")


if __name__ == "__main__":
    main()
